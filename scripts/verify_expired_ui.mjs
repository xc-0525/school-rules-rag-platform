import { chromium } from 'playwright'
const b = await chromium.launch(); const p = await b.newPage({ viewport: { width: 1440, height: 900 } })
await p.goto('http://127.0.0.1:8000/login', { waitUntil: 'networkidle' })
await p.fill("input[type='text']", 'demo'); await p.fill("input[type='password']", 'demo12345')
await p.keyboard.press('Enter'); await p.waitForURL('**/chat', { timeout: 20000 })
await p.goto('http://127.0.0.1:8000/services', { waitUntil: 'networkidle' })
await p.click(".el-tabs__item:has-text('图书馆预约')"); await p.waitForTimeout(1200)
console.log('默认行数:', await p.locator('.el-table__body tr').count())
console.log('开关:', (await p.locator('.el-switch').innerText().catch(() => '')), '| 文案:', (await p.locator('.panel-subtitle').last().innerText()).replace(/\s+/g, ' '))
await p.screenshot({ path: 'screenshots/50-my-reservations.png' })
await p.locator('.el-switch').first().click(); await p.waitForTimeout(500)
console.log('展开后:', (await p.locator('.el-table__body').innerText()).replace(/\s+/g, ' ').slice(0, 180))
await p.screenshot({ path: 'screenshots/51-my-reservations-expanded.png' })
await b.close()
