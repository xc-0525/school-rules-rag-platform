import { chromium } from 'playwright'
const b = await chromium.launch()
const p = await b.newPage({ viewport: { width: 1440, height: 900 } })
await p.goto('http://127.0.0.1:8000/login', { waitUntil: 'networkidle' })
await p.fill("input[type='text']", 'demo'); await p.fill("input[type='password']", 'demo12345')
await p.keyboard.press('Enter'); await p.waitForURL('**/chat', { timeout: 20000 })
await p.goto('http://127.0.0.1:8000/services', { waitUntil: 'networkidle' })
await p.click(".el-tabs__item:has-text('图书馆预约')"); await p.waitForTimeout(600)
await p.click('.location-card:has-text("自习区")'); await p.waitForTimeout(1500)
await p.click(".slot-row button:has-text('上午')")
await p.waitForSelector('.reserve-confirm-box', { timeout: 8000 })
await p.waitForTimeout(400)
await p.screenshot({ path: 'screenshots/44-booking-confirm.png' })
console.log('确认框文案：', (await p.locator('.reserve-confirm-box .el-message-box__message').innerText()).replace(/\n/g, ' | '))
await p.click(".reserve-confirm-box button:has-text('再想想')")
await p.waitForTimeout(600)
const rows = await p.locator('.el-table__body tr').count()
console.log('取消后预约条数：', rows)
await b.close()
